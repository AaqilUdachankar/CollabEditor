export function resolveTemplateKey(template: string): string {
  const norm = (template || '').toLowerCase().trim();
  const aliasMap: Record<string, string> = {
    'c++': 'cpp',
    'cxx': 'cpp',
    'ts': 'typescript',
    'js': 'javascript',
    'node': 'javascript',
    'py': 'python',
    'react': 'react-vite',
  };
  return aliasMap[norm] || norm;
}

